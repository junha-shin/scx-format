args <- commandArgs(trailingOnly = TRUE)
a <- readRDS(args[1]); b <- readRDS(args[2])
stopifnot(identical(colnames(a), colnames(b)), identical(rownames(a), rownames(b)))
stopifnot(isTRUE(all.equal(a[[]], b[[]], tolerance = 0)))
stopifnot(isTRUE(all.equal(a[["RNA"]][[]], b[["RNA"]][[]], tolerance = 0)))
for (layer in c("counts", "data")) stopifnot(max(abs(SeuratObject::LayerData(a, layer = layer) - SeuratObject::LayerData(b, layer = layer))) <= 1e-12)
for (name in SeuratObject::Reductions(a)) stopifnot(max(abs(SeuratObject::Embeddings(a[[name]]) - SeuratObject::Embeddings(b[[name]]))) <= 1e-12)
for (name in SeuratObject::Graphs(a)) stopifnot(max(abs(a[[name]] - b[[name]])) <= 1e-12)
cat("R benchmark round trip passed\n")
