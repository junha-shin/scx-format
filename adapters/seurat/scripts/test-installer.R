Sys.setenv(SCX_INSTALL_DEFINE_ONLY = "1")
source("install.R")
stopifnot(identical(.scx_binary_asset("Windows", "x86_64", "4.5"), "scxSeurat_0.1.5-windows-x86_64.zip"))
stopifnot(identical(.scx_binary_asset("Darwin", "aarch64", "4.5"), "scxSeurat_0.1.5-macos-arm64.tgz"))
stopifnot(identical(.scx_binary_asset("Linux", "x86_64", "4.5", c("ID=ubuntu", 'VERSION_ID="22.04"')), "scxSeurat_0.1.5-ubuntu22-x86_64.tar.gz"))
stopifnot(is.null(.scx_binary_asset("Windows", "x86_64", "4.4")))
stopifnot(is.null(.scx_binary_asset("Linux", "x86_64", "4.5", "ID=alpine")))
path <- tempfile(fileext = ".zip"); writeBin(charToRaw("package bytes"), path)
name <- basename(path)
correct <- paste0(digest::digest(path, algo = "sha256", file = TRUE), "  ", name)
stopifnot(isTRUE(.scx_verify_download(path, correct)))
writeBin(charToRaw("damaged package bytes"), path)
error <- tryCatch({.scx_verify_download(path, correct); "not rejected"}, error = conditionMessage)
stopifnot(grepl("Checksum mismatch", error, fixed = TRUE))
unlink(path)
cat("Installer platform selection and checksum protection passed\n")
