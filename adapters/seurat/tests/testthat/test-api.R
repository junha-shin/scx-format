testthat::test_that("basic and analysis APIs preserve the selected contract", {
  before <- tiny_seurat()
  parent <- tempfile(); dir.create(parent); on.exit(unlink(parent, recursive = TRUE))
  basic <- file.path(parent, "basic"); full <- file.path(parent, "full")
  testthat::expect_warning(write_scx(before, basic), "analysis=TRUE")
  after <- read_scx(basic)
  testthat::expect_identical(after[[]], before[[]])
  testthat::expect_identical(after[["RNA"]][[]], before[["RNA"]][[]])
  testthat::expect_length(SeuratObject::Reductions(after), 0L)
  testthat::expect_length(SeuratObject::Graphs(after), 0L)
  testthat::expect_equal(SeuratObject::LayerData(after, layer = "counts"), SeuratObject::LayerData(before, layer = "counts"), tolerance = 0)
  testthat::expect_equal(SeuratObject::LayerData(after, layer = "data"), SeuratObject::LayerData(before, layer = "data"), tolerance = 0)
  testthat::expect_silent(write_scx(before, full, analysis = TRUE))
  restored <- read_scx(full, assay_class = "Assay")
  testthat::expect_s4_class(restored[["RNA"]], "Assay")
  testthat::expect_length(SeuratObject::Reductions(restored), 1L)
  testthat::expect_length(SeuratObject::Graphs(restored), 1L)
  testthat::expect_error(write_scx(before, full), "already exists")
  testthat::expect_error(write_scx(before, file.path(parent, "bad"), analysis = "false"), "analysis must")
})
