"""Generate reviewable, self-contained scripts; --check detects stale bundles."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build():
    modules = {p.stem: p.read_text(encoding="utf-8") for p in sorted((ROOT / "src/scx").glob("*.py"))}
    python = '''# Generated by scripts/build_standalone.py; edit src/scx instead.
"""SCX without installation: import this file or run python scx.py --help."""
import importlib.abc as _abc
import importlib.util as _util
import sys as _sys

_SOURCES = ''' + repr(modules) + '''

class _BundledSCX(_abc.MetaPathFinder, _abc.Loader):
    def find_spec(self, fullname, path=None, target=None):
        if fullname == "_scx_standalone":
            return _util.spec_from_loader(fullname, self, is_package=True)
        if fullname.startswith("_scx_standalone.") and fullname.split(".")[-1] in _SOURCES:
            return _util.spec_from_loader(fullname, self)

    def create_module(self, spec):
        return None

    def exec_module(self, module):
        key = "__init__" if module.__name__ == "_scx_standalone" else module.__name__.split(".")[-1]
        module.__file__ = __file__ + "!/scx/" + key + ".py"
        exec(compile(_SOURCES[key], module.__file__, "exec"), module.__dict__)

if "_scx_standalone" not in _sys.modules:
    _sys.meta_path.insert(0, _BundledSCX())
from _scx_standalone import read_scx, write_scx, validate_scx, to_tsv, __version__

if __name__ == "__main__":
    from _scx_standalone.cli import main
    raise SystemExit(main())
'''
    rdir = ROOT / "adapters/seurat/R"
    scx = (rdir / "scx.R").read_text(encoding="utf-8")
    scx = scx[scx.index('.scx_json <-'):]
    r = '''# Generated by scripts/build_standalone.py; source this one file.
# No SCX package, compiler, Python, subprocess, or automatic installation.
(function(.target) {
  required <- c("SeuratObject", "Matrix", "jsonlite", "digest")
  missing <- required[!vapply(required, requireNamespace, logical(1), quietly = TRUE)]
  if (length(missing)) stop("Existing Seurat environment is missing: ", paste(missing, collapse=", "),
    ". No packages were installed. Use an environment containing these dependencies.")
  if (packageVersion("SeuratObject") < "5.0.0") stop("SeuratObject >=5 is required")
'''
    publication = (rdir / "publication.R").read_text(encoding="utf-8")
    publication = publication[publication.index('.scx_exists <-'):publication.index('.scx_publish <-')]
    publication = '\n'.join(line for line in publication.splitlines() if not line.startswith('.scx_rename_new <-'))
    for content in [publication,
                    (rdir / "validation.R").read_text(encoding="utf-8"), scx,
                    (rdir / "api.R").read_text(encoding="utf-8"),
                    (rdir / "tsv.R").read_text(encoding="utf-8"),
                    (ROOT / "standalone/r-runtime.R").read_text(encoding="utf-8")]:
        r += content + "\n"
    r += '''for (.name in c("read_scx", "write_scx", "validate_scx", "to_tsv")) assign(.name, get(.name), envir=.target)
invisible(NULL)
})(environment())
'''
    return {"standalone/scx.py": python, "standalone/scx.R": r}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, content in build().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                raise SystemExit(f"Stale bundle: {name}; run python scripts/build_standalone.py")
        else:
            path.write_text(content, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
